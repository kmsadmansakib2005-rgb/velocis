
import java.awt.*;
import java.util.List;
import javax.swing.*;
import javax.swing.border.*;
import javax.swing.table.DefaultTableModel;

public class LexicalAnalysisWindow extends JFrame {

    // Forest Graphite Theme
    private static final Color BG = new Color(23, 26, 24);
    private static final Color PANEL = new Color(37, 45, 40);
    private static final Color LIGHT_PANEL = new Color(49, 59, 52);
    private static final Color EDITOR = new Color(27, 32, 29);

    private static final Color TEXT = new Color(232, 238, 233);
    private static final Color MUTED = new Color(170, 183, 173);

    private static final Color ACCENT = new Color(117, 201, 154);
    private static final Color BLUE = new Color(125, 180, 205);
    private static final Color ERROR = new Color(235, 133, 125);

    private static final Color BORDER = new Color(65, 79, 69);

    public LexicalAnalysisWindow(
            List<String[]> tokens,
            String diagnostics
    ) {

        setTitle("Velocis Mini | Lexical Analysis");
        setIconImage(
                new ImageIcon(
                        getClass().getResource("Velocis-icon.png")
                ).getImage()
        );
        setSize(900, 600);
        setMinimumSize(new Dimension(650, 400));
        setLocationRelativeTo(null);
        setDefaultCloseOperation(JFrame.DISPOSE_ON_CLOSE);

        // Root panel
        JPanel root = new JPanel(new BorderLayout(12, 12));
        root.setBackground(BG);
        root.setBorder(new EmptyBorder(22, 24, 22, 24));

        // Header title
        JLabel title = new JLabel("LEXICAL ANALYSIS");
        title.setFont(new Font("Segoe UI", Font.BOLD, 27));
        title.setForeground(TEXT);

        JLabel subtitle = new JLabel(
                "Actual token stream generated by the Velocis Flex lexer"
        );
        subtitle.setFont(new Font("Segoe UI", Font.PLAIN, 15));
        subtitle.setForeground(MUTED);

        JPanel header = new JPanel();
        header.setOpaque(false);
        header.setLayout(new BoxLayout(header, BoxLayout.Y_AXIS));

        header.add(title);
        header.add(Box.createVerticalStrut(6));
        header.add(subtitle);

        // Token table
        String[] columns = {
                "LINE",
                "TOKEN TYPE",
                "LEXEME"
        };

        DefaultTableModel model = new DefaultTableModel(columns, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        for (String[] token : tokens) {
            model.addRow(token);
        }

        JTable table = new JTable(model);

        table.setFont(new Font("Consolas", Font.PLAIN, 16));
        table.setForeground(TEXT);
        table.setBackground(EDITOR);
        table.setGridColor(BORDER);
        table.setRowHeight(36);

        table.setSelectionBackground(new Color(58, 91, 70));
        table.setSelectionForeground(Color.WHITE);

        table.setFillsViewportHeight(true);
        table.setShowGrid(true);
        table.setIntercellSpacing(new Dimension(1, 1));

        // Table header
        table.getTableHeader().setFont(
                new Font("Segoe UI", Font.BOLD, 14)
        );

        table.getTableHeader().setForeground(ACCENT);
        table.getTableHeader().setBackground(PANEL);
        table.getTableHeader().setPreferredSize(
                new Dimension(0, 40)
        );
        table.getTableHeader().setReorderingAllowed(false);

        table.getColumnModel().getColumn(0).setPreferredWidth(75);
        table.getColumnModel().getColumn(1).setPreferredWidth(220);
        table.getColumnModel().getColumn(2).setPreferredWidth(450);

        // Table scroll pane
        JScrollPane scroll = new JScrollPane(table);

        scroll.setBorder(
                new LineBorder(BORDER, 1, true)
        );

        scroll.getViewport().setBackground(EDITOR);

        // Token count
        JLabel count = new JLabel(
                "TOTAL TOKENS: " + tokens.size()
        );

        count.setFont(new Font("Segoe UI", Font.BOLD, 14));
        count.setForeground(ACCENT);

        // Lexical diagnostics
        JTextArea errorArea = new JTextArea();

        errorArea.setEditable(false);
        errorArea.setFont(new Font("Consolas", Font.PLAIN, 14));
        errorArea.setForeground(ERROR);
        errorArea.setBackground(EDITOR);

        errorArea.setCaretColor(TEXT);
        errorArea.setBorder(
                new EmptyBorder(8, 10, 8, 10)
        );

        errorArea.setText(
                diagnostics == null || diagnostics.isBlank()
                        ? "No lexical diagnostics."
                        : diagnostics
        );

        errorArea.setLineWrap(true);
        errorArea.setWrapStyleWord(true);

        JScrollPane errorScroll = new JScrollPane(errorArea);

        errorScroll.setPreferredSize(
                new Dimension(0, 100)
        );

        errorScroll.setBorder(
                BorderFactory.createTitledBorder(
                        new LineBorder(BORDER, 1, true),
                        "LEXICAL DIAGNOSTICS",
                        TitledBorder.LEFT,
                        TitledBorder.TOP,
                        new Font("Segoe UI", Font.BOLD, 13),
                        BLUE
                )
        );

        errorScroll.getViewport().setBackground(EDITOR);

        // Footer
        JPanel footer = new JPanel(new BorderLayout(0, 9));
        footer.setOpaque(false);

        footer.add(count, BorderLayout.NORTH);
        footer.add(errorScroll, BorderLayout.CENTER);

        // Assemble window
        root.add(header, BorderLayout.NORTH);
        root.add(scroll, BorderLayout.CENTER);
        root.add(footer, BorderLayout.SOUTH);

        setContentPane(root);
    }
}
