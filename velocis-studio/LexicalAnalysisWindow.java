
import java.awt.*;
import javax.swing.*;
import javax.swing.table.DefaultTableModel;

public class LexicalAnalysisWindow extends JFrame {

    public LexicalAnalysisWindow() {

        setTitle("Velocis Mini | Lexical Analysis");
        setSize(850, 500);
        setMinimumSize(new Dimension(650, 350));
        setLocationRelativeTo(null);
        setDefaultCloseOperation(JFrame.DISPOSE_ON_CLOSE);

        // Main layout
        JPanel mainPanel = new JPanel(new BorderLayout(10, 10));
        mainPanel.setBorder(
            BorderFactory.createEmptyBorder(15, 15, 15, 15)
        );

        // Header
        JLabel title = new JLabel("LEXICAL ANALYSIS");
        title.setFont(new Font("Segoe UI", Font.BOLD, 22));

        JLabel subtitle = new JLabel(
            "Inspect tokens generated by the Velocis lexer."
        );
        subtitle.setFont(new Font("Segoe UI", Font.PLAIN, 13));

        JPanel header = new JPanel(new BorderLayout(5, 5));
        header.add(title, BorderLayout.NORTH);
        header.add(subtitle, BorderLayout.SOUTH);

        // Token table: real results will be connected later
        String[] columns = {
            "Line", "Token Type", "Lexeme"
        };

        DefaultTableModel model = new DefaultTableModel(columns, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        JTable tokenTable = new JTable(model);
        tokenTable.setFont(new Font("Consolas", Font.PLAIN, 14));
        tokenTable.setRowHeight(28);
        tokenTable.getTableHeader().setFont(
            new Font("Segoe UI", Font.BOLD, 13)
        );

        JScrollPane tableScroll = new JScrollPane(tokenTable);
        tableScroll.setBorder(
            BorderFactory.createTitledBorder("Token Stream")
        );

        // Honest status: no fake token results
        JLabel status = new JLabel(
            "Waiting for compiler connection."
        );
        status.setBorder(
            BorderFactory.createEmptyBorder(5, 0, 0, 0)
        );

        mainPanel.add(header, BorderLayout.NORTH);
        mainPanel.add(tableScroll, BorderLayout.CENTER);
        mainPanel.add(status, BorderLayout.SOUTH);

        setContentPane(mainPanel);
    }

    public static void main(String[] args) {
        SwingUtilities.invokeLater(() -> {
            LexicalAnalysisWindow window =
                new LexicalAnalysisWindow();
            window.setVisible(true);
        });
    }
}
